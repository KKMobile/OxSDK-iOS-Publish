#!/usr/bin/env python3
"""Prepare a Core binary SPM release locally. Never commits, tags, or uploads."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import shutil
import subprocess
import sys
import uuid
import zipfile

ROOT = Path(__file__).resolve().parents[1]
FRAMEWORKS = ["Foundation", "UIKit", "AppTrackingTransparency",
              "SystemConfiguration", "CoreTelephony", "Security"]


def run(args, *, cwd=None, log=None):
    print("Running:", " ".join(map(str, args)), flush=True)
    if log:
        with log.open("w") as stream:
            result = subprocess.run(list(map(str, args)), cwd=cwd,
                                    stdout=stream, stderr=subprocess.STDOUT)
        if result.returncode:
            lines = log.read_text(errors="replace").splitlines()
            print("\n".join(lines[-45:]), file=sys.stderr)
            raise SystemExit(f"Command failed ({result.returncode}); full log: {log}")
    else:
        return subprocess.check_output(list(map(str, args)), cwd=cwd, text=True).strip()


def declarations(dependencies):
    packages = ",\n".join(
        f'        .package(url: "{d["url"]}", exact: "{d["version"]}")'
        for d in dependencies)
    products = ",\n".join(
        f'                .product(name: "{d["product"]}", '
        f'package: "{d["url"].rsplit("/", 1)[1].removesuffix(".git")}")'
        for d in dependencies)
    return packages, products


def manifest(dependencies, binary_declaration):
    packages, products = declarations(dependencies)
    frameworks = ",\n".join(f'                .linkedFramework("{name}")'
                              for name in FRAMEWORKS)
    return f'''// swift-tools-version: 5.9
// Generated by scripts/prepare_spm_core_release.py.
import PackageDescription

let package = Package(
    name: "OxSDK",
    defaultLocalization: "en",
    platforms: [.iOS(.v15)],
    products: [.library(name: "OxSdkCore", targets: ["OxSdkCoreSupport"])],
    dependencies: [
{packages}
    ],
    targets: [
        {binary_declaration},
        .target(
            name: "OxSdkCoreSupport",
            dependencies: [
                .target(name: "OxSdkCore"),
{products}
            ],
            path: "SPM/CoreSupport",
            resources: [
                .copy("Resources/OxSdkRes.bundle"),
                .copy("Resources/Language.bundle"),
                .copy("Resources/PrivacyInfo.xcprivacy")
            ],
            publicHeadersPath: "include",
            linkerSettings: [
{frameworks}
            ]
        )
    ]
)
'''


def stage_source(source, stage, dependencies):
    """Copy only Core into an isolated build; original source is never edited."""
    shutil.copytree(source / "iOS/Core", stage / "iOS/Core",
                    ignore=shutil.ignore_patterns(".DS_Store", "include", "*.podspec"))
    headers = {}
    include = stage / "include"
    include.mkdir()
    for header in sorted((stage / "iOS/Core").rglob("*.h")):
        if header.name in headers:
            raise SystemExit(f"Duplicate Core header name: {header.name}")
        headers[header.name] = header
        relative = os.path.relpath(header, include)
        (include / header.name).write_text(f'#pragma once\n#import "{relative}"\n')
    with (include / "OxSdkCore.h").open("a") as stream:
        stream.write('#import "OxPreferenceManager.h"\n')

    # The release support target provides the resource bundle accessor. Do not
    # bake source SPM's bundle name or an absolute developer path into the binary.
    util = stage / "iOS/Core/nativeinterstitial/OxResBundleUtil.m"
    text = util.read_text()
    old = "#if SWIFT_PACKAGE\n    return SWIFTPM_MODULE_BUNDLE;"
    if text.count(old) != 1:
        raise SystemExit("Core resource accessor changed; review binary resource adaptation.")
    text = text.replace(old, "#if defined(OXSDK_BINARY_DISTRIBUTION)\n"
                        "    extern NSBundle *OxSDKCoreDistributionResourceBundle(void);\n"
                        "    return OxSDKCoreDistributionResourceBundle();\n"
                        "#elif SWIFT_PACKAGE\n    return SWIFTPM_MODULE_BUNDLE;")
    util.write_text(text)
    packages, products = declarations(dependencies)
    (stage / "Package.swift").write_text(f'''// swift-tools-version: 5.9
import PackageDescription
let package = Package(
    name: "OxCoreBinaryBuild",
    platforms: [.iOS(.v15)],
    products: [.library(name: "OxSdkCore", targets: ["OxSdkCore"])],
    dependencies: [
{packages}
    ],
    targets: [.target(
        name: "OxSdkCore",
        dependencies: [
{products}
        ],
        path: ".",
        sources: ["iOS/Core"],
        publicHeadersPath: "include",
        cSettings: [.define("OXSDK_BINARY_DISTRIBUTION")]
    )]
)
''')
    if (source / "Package.resolved").exists():
        pins = json.loads((source / "Package.resolved").read_text())
        expected = {d["url"].lower(): d["version"] for d in dependencies}
        actual = {p["location"].lower(): p["state"].get("version") for p in pins["pins"]}
        if actual != expected:
            raise SystemExit("Source Package.resolved differs from SPM/core-dependencies.json; review versions first.")
        shutil.copy2(source / "Package.resolved", stage / "Package.resolved")
    return headers


def framework(binary_object, headers, destination, version):
    (destination / "Headers").mkdir(parents=True)
    (destination / "Modules").mkdir()
    for name, header in headers.items():
        shutil.copy2(header, destination / "Headers" / name)
    with (destination / "Headers/OxSdkCore.h").open("a") as stream:
        stream.write('\n#import "OxPreferenceManager.h"\n')
    (destination / "Headers/OxSdkCore-umbrella.h").write_text(
        '#import <Foundation/Foundation.h>\n'
        + ''.join(f'#import "{name}"\n' for name in sorted(headers)))
    (destination / "Modules/module.modulemap").write_text(
        'framework module OxSdkCore {\n'
        '    umbrella header "OxSdkCore-umbrella.h"\n'
        '    export *\n'
        '    module * { export * }\n}\n')
    with (destination / "Info.plist").open("wb") as stream:
        plistlib.dump({
            "CFBundleDevelopmentRegion": "en",
            "CFBundleExecutable": "OxSdkCore",
            "CFBundleIdentifier": "com.oxsdk.core",
            "CFBundleInfoDictionaryVersion": "6.0",
            "CFBundleName": "OxSdkCore",
            "CFBundlePackageType": "FMWK",
            "CFBundleShortVersionString": version.split("-", 1)[0],
            "CFBundleVersion": "1",
            "MinimumOSVersion": "15.0",
        }, stream)
    # Archive ONLY the Core target object, never its transitive third-party SDKs.
    run(["xcrun", "libtool", "-static", "-o", destination / "OxSdkCore", binary_object])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True,
                        help="Mavl-AdSDK-Game source repository (read only)")
    parser.add_argument("--version", required=True, help="SPM SemVer, e.g. 0.1.0-spm.1")
    parser.add_argument("--repository", default="KKMobile/OxSDK-iOS-Publish")
    parser.add_argument("--package-cache", type=Path,
                        help="Optional existing Xcode SourcePackages directory")
    args = parser.parse_args()
    if not re.fullmatch(r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?", args.version):
        parser.error("--version must be a three-component SemVer (optional prerelease)")
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", args.repository):
        parser.error("--repository must be owner/repository")
    source = args.source.resolve()
    if not (source / "iOS/Core/OxSdkCore.h").is_file():
        parser.error("--source does not contain iOS/Core/OxSdkCore.h")
    output = ROOT / "SPM/Artifacts" / args.version
    if output.exists():
        parser.error(f"Refusing to replace an existing release: {output}")
    work = ROOT / ".build/spm-core" / (args.version + "-" + uuid.uuid4().hex[:8])
    stage = work / "source"
    stage.mkdir(parents=True)
    dependencies = json.loads((ROOT / "SPM/core-dependencies.json").read_text())
    headers = stage_source(source, stage, dependencies)
    cache = args.package_cache.resolve() if args.package_cache else (work / "SourcePackages")
    builds = []
    for platform, destination, suffix in [
        ("device", "generic/platform=iOS", "iphoneos"),
        ("simulator", "generic/platform=iOS Simulator", "iphonesimulator"),
    ]:
        derived = work / platform
        run(["xcodebuild", "-scheme", "OxCoreBinaryBuild", "-configuration", "Release",
             "-destination", destination, "-derivedDataPath", derived,
             "-clonedSourcePackagesDirPath", cache,
             "-disableAutomaticPackageResolution", "CODE_SIGNING_ALLOWED=NO",
             "ONLY_ACTIVE_ARCH=NO", "GCC_GENERATE_DEBUGGING_SYMBOLS=NO",
             "DEBUG_INFORMATION_FORMAT=dwarf", "build"],
            cwd=stage, log=work / (platform + ".log"))
        binary_object = derived / f"Build/Products/Release-{suffix}/OxSdkCore.o"
        if not binary_object.is_file():
            raise SystemExit(f"Expected Core target object missing: {binary_object}")
        product = work / "frameworks" / platform / "OxSdkCore.framework"
        framework(binary_object, headers, product, args.version)
        builds += ["-framework", product]
    artifact = work / "OxSdkCore.xcframework"
    run(["xcodebuild", "-create-xcframework", *builds, "-output", artifact])
    info = plistlib.loads((artifact / "Info.plist").read_bytes())
    slices = {(lib["SupportedPlatform"], lib.get("SupportedPlatformVariant", "")):
              set(lib["SupportedArchitectures"]) for lib in info["AvailableLibraries"]}
    if slices.get(("ios", "")) != {"arm64"} or slices.get(("ios", "simulator")) != {"arm64", "x86_64"}:
        raise SystemExit(f"Unexpected XCFramework slices: {slices}")
    output.mkdir(parents=True)
    archive = output / "OxSdkCore.xcframework.zip"
    run(["ditto", "-c", "-k", "--keepParent", "--norsrc", artifact, archive])
    with zipfile.ZipFile(archive) as zipped:
        forbidden = [name for name in zipped.namelist()
                     if Path(name).suffix in {".m", ".mm", ".swift", ".c", ".cpp"}]
        if forbidden:
            raise SystemExit(f"Implementation files in release archive: {forbidden}")
    checksum = run(["swift", "package", "compute-checksum", archive])
    if checksum != hashlib.sha256(archive.read_bytes()).hexdigest():
        raise SystemExit("Archive checksum mismatch")
    url = f"https://github.com/{args.repository}/releases/download/{args.version}/{archive.name}"
    release_manifest = manifest(dependencies,
        f'.binaryTarget(name: "OxSdkCore",\n'
        f'            url: "{url}",\n'
        f'            checksum: "{checksum}")')
    # Preserve the previous manifest until compilation and artifact checks succeed.
    (ROOT / "Package.swift").write_text(release_manifest)
    resources = ROOT / "SPM/CoreSupport/Resources"
    resources.mkdir(exist_ok=True)
    for name in ["OxSdkRes.bundle", "Language.bundle", "PrivacyInfo.xcprivacy"]:
        original = source / "SPM/Core/Resources" / name
        target = resources / name
        if target.is_dir():
            shutil.rmtree(target)
        if original.is_dir():
            shutil.copytree(original, target, ignore=shutil.ignore_patterns(".DS_Store"))
        else:
            shutil.copy2(original, target)
    if (stage / "Package.resolved").exists():
        shutil.copy2(stage / "Package.resolved", ROOT / "Package.resolved")

    # Same support sources and dependency graph, using the artifact on disk only
    # for validation before the remote Release URL exists.
    validation = work / "validation"
    validation.mkdir()
    shutil.copytree(ROOT / "SPM/CoreSupport", validation / "SPM/CoreSupport")
    shutil.copytree(artifact, validation / "Artifacts/OxSdkCore.xcframework")
    (validation / "Package.swift").write_text(manifest(dependencies,
        '.binaryTarget(name: "OxSdkCore", path: "Artifacts/OxSdkCore.xcframework")'))
    if (ROOT / "Package.resolved").exists():
        shutil.copy2(ROOT / "Package.resolved", validation / "Package.resolved")
    metadata = {"version": args.version, "url": url, "checksum": checksum,
                "archive": str(archive), "xcframework": str(artifact),
                "validation_package": str(validation), "package_cache": str(cache),
                "source_commit": run(["git", "rev-parse", "HEAD"], cwd=source),
                "source_status": run(["git", "status", "--porcelain"], cwd=source)}
    (output / "release.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps(metadata, indent=2))
    print("Prepared locally. No Git commit, tag, push, or upload was performed.")


if __name__ == "__main__":
    main()
